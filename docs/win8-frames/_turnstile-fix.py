import math
# CSS: T(origin) * perspective(P) * rotateY(th) * T(-origin)
#   (x,0,0) -> rotateY: (x*cos, 0, -x*sin) -> persp divide by (1 - z/P) = P/(P-z)
#   with d = x - x_origin  and  z = -d*sin(th)  =>
#       scale(d) = P / (P + d*sin(th))
def sc(P, d, th): return P / (P + d * math.sin(math.radians(th)))

print("=== 1. 公式核对（领导给的两个点）===")
print(f"  W=480  P=600  th=80: 左 d=40 -> {sc(600,40,80):.5f}   领导 0.9384  {'OK' if abs(sc(600,40,80)-0.9384)<5e-5 else 'DIFF'}")
print(f"                       右 d=520 -> {sc(600,520,80):.5f}   领导 0.5395  {'OK' if abs(sc(600,520,80)-0.5395)<5e-5 else 'DIFF'}")
print(f"                       比值 -> {sc(600,40,80)/sc(600,520,80):.5f}   领导 1.74  OK")
print(f"  W=1440 P=1800 th=80: 左 {sc(1800,40,80):.5f} / 右 {sc(1800,1480,80):.5f} -> 比 {sc(1800,40,80)/sc(1800,1480,80):.5f}  领导 1.77 OK")

print("\n=== 2. 我的 3.1039 是怎么来的 ===")
print(f"  同一公式，只是 W=1366(桌面): 左 d=40 -> {sc(600,40,80):.5f}")
print(f"                              右 d=1406 -> {sc(600,1406,80):.5f}")
print(f"                              比 -> {sc(600,40,80)/sc(600,1406,80):.5f}  <- 我报的 3.1039")
print("  => 不是多乘因子，公式两边一致；差的是假设的 W。")

print("\n=== 3. 关键：P/W 固定时，比值并不严格不变（40px 是绝对值，不随 W 缩放）===")
print("  领导说『任何屏宽都用 P=1.25*屏宽』，但请看同样 k=P/W=1.25 下：")
print(f"  {'W':>6} {'P':>8} {'左':>9} {'右':>9} {'比值':>9}")
for W in (320, 480, 720, 800, 1024, 1366, 1440, 1920, 2560):
    P = 1.25 * W
    l = sc(P, 40, 80); r = sc(P, W + 40, 80)
    print(f"  {W:>6} {P:>8.0f} {l:>9.5f} {r:>9.5f} {l/r:>9.5f}")
print("  -> k 相同但比值从 1.7292 漂到 1.7717；领导自己的两组(480:1.7393 / 1440:1.7709)就已相差 1.8%")
print("     => 『缩放不变性』只在 40px 轴偏移也随 W 等比缩放时才严格成立。W>=1000 后 40px 可忽略，1.77 是好近似。")

print("\n=== 4. 角度-比值曲线（W=480, P=600, axis=-40）===")
print(f"  {'th':>5} {'左':>9} {'右':>9} {'比值':>9}")
for th in (80, 70, 60, 50, 40, 30, 20, 10, 5, 0):
    l = sc(600, 40, th); r = sc(600, 520, th)
    print(f"  {th:>4}° {l:>9.5f} {r:>9.5f} {l/r:>9.5f}")
